// Writes prisma/postgres/schema.prisma from prisma/schema.prisma with the Postgres provider.
// Local dev keeps SQLite (prisma/schema.prisma). prisma.config.ts picks the Postgres copy
// whenever DATABASE_URL starts with postgres:// or postgresql://.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const source = readFileSync(path.join(root, "prisma/schema.prisma"), "utf8");
const out = source
  .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"')
  .replace(/output\s*=\s*"\.\.\/src\/generated\/prisma"/, 'output   = "../../src/generated/prisma"');
if (out === source || !out.includes('"postgresql"') || !out.includes("../../src/generated/prisma")) {
  console.error("prisma-schema: could not rewrite prisma/schema.prisma for Postgres");
  process.exit(1);
}
mkdirSync(path.join(root, "prisma/postgres"), { recursive: true });
writeFileSync(
  path.join(root, "prisma/postgres/schema.prisma"),
  `// GENERATED by scripts/prisma-schema.mjs from prisma/schema.prisma. Do not edit.\n${out}`,
);
console.log("prisma-schema: wrote prisma/postgres/schema.prisma");
